/** The exactly-one-of classification vocabulary for an implementation claim (README §4). */
const UI01_CLASSIFICATIONS = ['true', 'false', 'unreachable', 'stale', 'not_claimed'];

/** The severity vocabulary (README §5). */
const UI01_SEVERITIES = ['critical', 'high', 'medium', 'low', 'observation'];

/** Every phase a defect may be assigned to. A defect owned by "UI-01" would be a phase violation. */
const UI01_OWNER_PHASES = [
    'UI-02', 'UI-03', 'UI-04', 'UI-05', 'UI-06', 'UI-07', 'UI-08', 'UI-09', 'UI-10',
    'UI-11', 'UI-12', 'UI-13', 'UI-14', 'UI-15', 'UI-16', 'UI-17',
