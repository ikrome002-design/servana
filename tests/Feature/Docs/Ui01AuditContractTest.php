it('commits no raw HAR and no credential material in the network evidence', function (): void {
    $files = glob(base_path(UI01_PROOF_DIR.'/network/*')) ?: [];

    expect($files)->not->toBeEmpty('No network evidence was committed.');

    foreach ($files as $file) {
        expect(pathinfo($file, PATHINFO_EXTENSION))->toBe('json', 'Only sanitized JSON evidence may be committed.');
        expect(basename($file))->not->toContain('.har');

        $contents = (string) file_get_contents($file);

        foreach (['set-cookie', 'authorization:', 'bearer ey', 'x-csrf-token', 'xsrf-token'] as $marker) {
            expect(str_contains(strtolower($contents), $marker))->toBeFalse(
                basename($file)." contains '{$marker}'. Network evidence must be sanitized before it is committed.",
            );
        }
    }
});
