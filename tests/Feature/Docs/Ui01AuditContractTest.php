/*
 |==============================================================================
 | Phase UI-01 — as-built audit contract enforcement.
 |
 | UI-01 produces evidence, not fixes. Its value therefore rests entirely on the evidence being
 | complete, well-formed, deterministic and honest. This guard enforces exactly that, and nothing
 | about product quality: it never asserts a page renders, a defect is fixed, or a count improved.
 |
 | It is OFFLINE and deterministic. It reads the committed audit artifacts, the committed evidence
 | capture and the filesystem. It does not start a browser, a container or a build. The artifacts
 | it reads are regenerated by `node scripts/audit-ui-as-built.mjs`, whose `--check` mode proves a
 | second pass produces no diff.
 |
 | The one property it enforces about the FINDINGS is the phase boundary: every product defect must
 | remain open and must name a future owner phase. A UI-01 pull request that closed a product
 | defect would have exceeded its own mandate, and this test fails on it.
 */

const UI01_AUDIT_DIR = 'docs/frontend/audits/ui-01';
const UI01_PROOF_DIR = 'docs/proof/ui-01';
const UI01_REGISTER = UI01_AUDIT_DIR.'/defect-register.csv';

/** The six machine-readable artifacts the phase is required to produce. */
const UI01_ARTIFACTS = [
    'audit-manifest.json',
    'baseline-screenshot-manifest.json',
    'navigation-role-audit.json',
    'route-component-page-audit.json',
    'served-build-provenance.json',
    'theme-asset-legal-audit.json',
];

/** The eight canonical accounts and their binding authenticated page counts (UI/UX plan §0). */
const UI01_ACCOUNTS = [
    'super_administrator' => 22,
    'merchant_administrator' => 23,
    'merchant_branch' => 18,
    'merchant_human_resource' => 19,
    'merchant_finance' => 24,
    'merchant_front_office' => 19,
