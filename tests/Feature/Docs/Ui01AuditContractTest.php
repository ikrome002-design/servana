// 5. The defect register is complete, and the phase boundary held
// ---------------------------------------------------------------------------------------------

it('records a complete, well-formed defect register', function (): void {
    $rows = ui01Register();

    expect($rows)->not->toBeEmpty('The defect register is empty.');

    $ids = [];
    foreach ($rows as $row) {
        expect($row['id'])->toMatch('/^UI01-[A-Z0-9]+-\d{3}$/');
        expect(in_array($row['id'], $ids, true))->toBeFalse("Defect id {$row['id']} appears twice.");
        $ids[] = $row['id'];

        expect(in_array($row['severity'], UI01_SEVERITIES, true))->toBeTrue(
            "Defect {$row['id']} has severity {$row['severity']}, which is not in the permitted vocabulary.",
        );
        expect(in_array($row['root_cause_status'], ['proven', 'unproven'], true))->toBeTrue(
            "Defect {$row['id']} has root_cause_status {$row['root_cause_status']}.",
        );

        foreach (['observed_problem', 'governing_requirement', 'expected_behavior', 'actual_behavior', 'evidence_paths', 'affected_accounts', 'future_acceptance_test'] as $field) {
            expect($row[$field])->not->toBe('', "Defect {$row['id']} has an empty {$field}.");
        }
    }
});

it('cites at least one evidence path that exists for every defect', function (): void {
    foreach (ui01Register() as $row) {
        $paths = array_filter(array_map(
            // Evidence entries carry a parenthesised pointer to the field inside the file.
            static fn (string $entry): string => trim(preg_replace('/\s*\(.*$/', '', trim($entry)) ?? ''),
            explode(';', $row['evidence_paths']),
        ));

        expect($paths)->not->toBeEmpty("Defect {$row['id']} cites no evidence path.");

        $found = false;
        foreach ($paths as $path) {
            if (file_exists(base_path($path)) || is_dir(base_path($path))) {
                $found = true;

                break;
            }
        }

        expect($found)->toBeTrue("Defect {$row['id']} cites no evidence path that exists: {$row['evidence_paths']}");
    }
});

it('leaves every product defect open and assigned to a future phase', function (): void {
    foreach (ui01Register() as $row) {
        // UI-01 resolves the absence of trustworthy evidence, never the defects it discovers. A
        // closed row here would mean the audit branch also carried a product fix.
        expect($row['status'])->toBe('open', "Defect {$row['id']} is not open. UI-01 must not fix product defects.");

        expect(in_array($row['future_owner_phase'], UI01_OWNER_PHASES, true))->toBeTrue(
            "Defect {$row['id']} names owner phase {$row['future_owner_phase']}, which is not a valid future owner.",
        );

        expect($row['entry_condition'])->not->toBe('', "Defect {$row['id']} has no entry condition.");
    }
});

