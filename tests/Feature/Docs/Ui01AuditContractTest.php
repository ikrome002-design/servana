];

/** @return array<string, mixed> */
function ui01Artifact(string $name): array
{
    $path = base_path(UI01_AUDIT_DIR."/{$name}");

    expect(file_exists($path))->toBeTrue(
        "{$name} is missing. Run: node scripts/audit-ui-as-built.mjs",
    );

    /** @var array<string, mixed> $decoded */
    $decoded = json_decode((string) file_get_contents($path), true, flags: JSON_THROW_ON_ERROR);

    return $decoded;
}

/**
 * Parse the defect register as strict RFC 4180. A hand-authored CSV whose prose contains commas
 * is exactly the sort of file that silently loses a column, so the parse is explicit rather than
 * delegated to str_getcsv line by line.
 *
 * @return list<array<string, string>>
 */
function ui01Register(): array
{
    $path = base_path(UI01_REGISTER);

    expect(file_exists($path))->toBeTrue('The UI-01 defect register is missing.');

    $handle = fopen($path, 'r');
    expect($handle)->not->toBeFalse();

    $header = fgetcsv($handle, escape: '');
    expect($header)->toBeArray();

    $rows = [];
    while (($row = fgetcsv($handle, escape: '')) !== false) {
        if ($row === [null]) {
            continue;
        }

        expect(count($row))->toBe(
            count($header),
            "Defect register row '{$row[0]}' has ".count($row).' fields, expected '.count($header).'.',
        );

        /** @var array<string, string> $assoc */
        $assoc = array_combine($header, $row);
        $rows[] = $assoc;
    }

    fclose($handle);

    return $rows;
}

