it('hashes every artifact and evidence input in the manifest', function (): void {
    $manifest = ui01Artifact('audit-manifest.json');

    /** @var list<array{path: string, sha256: string}> $artifacts */
    $artifacts = $manifest['artifacts'];
    $hashed = array_column($artifacts, 'sha256', 'path');

    foreach (UI01_ARTIFACTS as $name) {
        if ($name === 'audit-manifest.json') {
            continue; // A manifest cannot contain its own hash.
        }

        $path = UI01_AUDIT_DIR."/{$name}";
        // `toHaveKey`'s second argument is an expected VALUE, not a message — assert presence first.
        expect(array_key_exists($path, $hashed))->toBeTrue("{$name} is not hashed in the audit manifest.");
        expect($hashed[$path])->toBe(
            hash_file('sha256', base_path($path)),
            "{$name} does not match its manifest hash. Run: node scripts/audit-ui-as-built.mjs",
        );
    }

    expect(array_key_exists(UI01_REGISTER, $hashed))->toBeTrue('The defect register is not hashed in the audit manifest.');
    expect($hashed[UI01_REGISTER])->toBe(hash_file('sha256', base_path(UI01_REGISTER)));

    // Every source the audit read is hashed too, so a later phase can prove which inputs produced
    // these conclusions rather than assuming the inputs never moved.
    /** @var list<array{path: string, present: bool, sha256: ?string}> $sources */
    $sources = $manifest['source_inputs'];
    expect($sources)->not->toBeEmpty();

    foreach ($sources as $source) {
        if ($source['present'] !== true) {
            continue;
        }

        // The recorded hash must be a real digest — that is what makes "which inputs produced
        // these conclusions" answerable later.
        expect($source['sha256'])->toMatch('/^[0-9a-f]{64}$/');

        if ($source['sha256'] === hash_file('sha256', base_path($source['path']))) {
            continue;
        }

        /*
         | The input has moved since the audit. That is EXPECTED for shared, living sources — the
         | screen inventory grows every time a phase registers a route — and demanding they stay
         | byte-frozen would either freeze the programme or force a later phase to rewrite UI-01's
         | evidence, which §7.2 forbids. What must never move is the audit's OWN evidence.
         */
        $isUi01Evidence = str_starts_with($source['path'], 'docs/frontend/audits/ui-01/')
            || str_starts_with($source['path'], 'docs/proof/ui-01/');

        expect($isUi01Evidence)->toBeFalse(
            "UI-01's own evidence changed after the audit was generated: {$source['path']}. "
                .'Historical audit evidence is immutable.',
        );
    }
});

