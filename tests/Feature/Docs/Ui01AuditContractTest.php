it('provenances every baseline screenshot and represents every surface it could not capture', function (): void {
    $manifest = ui01Artifact('baseline-screenshot-manifest.json');

    /** @var list<array<string, mixed>> $shots */
    $shots = $manifest['screenshots'];

    expect($shots)->not->toBeEmpty('No baseline screenshots were recorded.');

    foreach ($shots as $shot) {
        expect(['captured', 'unreachable', 'not_configured', 'failed'])->toContain($shot['result']);
        expect($shot['source_commit'])->toMatch('/^[0-9a-f]{40}$/');
        expect($shot['viewport_width'])->toBeGreaterThan(0);

        if ($shot['result'] !== 'captured') {
            // An absent surface is evidence. It must be represented, and it must not claim a file.
            expect($shot['path'])->toBeNull("A non-captured screenshot for {$shot['route']} must not name a file.");

            continue;
        }

        expect($shot['path'])->toBeString();
        expect(file_exists(base_path((string) $shot['path'])))->toBeTrue("Screenshot {$shot['path']} is missing.");
        expect($shot['sha256'])->toBe(
            hash_file('sha256', base_path((string) $shot['path'])),
            "Screenshot {$shot['path']} does not match its recorded hash.",
        );
    }
});

