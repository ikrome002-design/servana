// 3. Every page claim is classified, and the two registers stay separate
// ---------------------------------------------------------------------------------------------

it('classifies every implementation claim exactly once from the permitted vocabulary', function (): void {
    $audit = ui01Artifact('route-component-page-audit.json');

    /** @var list<array<string, mixed>> $claims */
    $claims = $audit['implementation_claims'];

    $inventory = json_decode(
        (string) file_get_contents(base_path('docs/frontend/screens/inventory.json')),
        true,
        flags: JSON_THROW_ON_ERROR,
    );

    /*
     | The UI-01 audit is a HISTORICAL SNAPSHOT: it classified every screen-inventory row that
     | existed on 2026-07-29, and §7.2 of the corrective programme forbids re-running that
     | classification. Asserting an exact count against the LIVE inventory therefore made a later
     | phase unable to register a new screen without either rewriting UI-01's evidence or being
     | blocked — which is the opposite of what this guard is for.
     |
     | The invariant that actually matters is unchanged and is asserted directly: every row that
     | existed AT AUDIT TIME is classified, and no claim refers to a screen that does not exist.
     | Rows added afterwards belong to the phase that added them and carry their own proof.
     */
    /*
     | REGISTERED REMOVALS. A screen may leave the inventory, but never silently: the UI-01
     | register is frozen, so a claim it carries that no longer resolves must be accounted for
     | here, by the phase that removed the screen, with the evidence for the removal.
     |
     | This is an explicit register, not an exemption. A removal nobody recorded still fails, and
     | the case below fails again the moment a registered key reappears in the inventory — which
     | forces the entry out rather than letting it rot.
     */
    $registeredRemovals = [
        // Phase UI-07, defect UI07-ROUTE-001. Each of these four routes rendered
        // `DashboardStub.vue` — a six-line component reading "Phase 4 stub — implementation in
        // later phases" — so four contract pages were exposed as live routes that implemented
        // nothing, which UI/UX plan §7.2 and §13.5 forbid. The routes and the dead components
        // were removed; the canonical navigation contract reserves each page's route identity
        // with `implementation_status: planned` and a named owner phase, so none of them can be
        // silently renamed or quietly forgotten.
        // `platform-dashboard` is DELIBERATELY ABSENT from this list. UI-07 removed its
        // placeholder route and named UI-08 as the owner; UI-08 Increment 9B delivered the real
        // page — a server-side aggregate read at `/dashboard` — so the screen is back in the
        // inventory legitimately and the resurrection guard below is what forced this entry out.
        // That is the register working exactly as designed: a removal is temporary custody, and
        // the entry expires when the owner phase delivers.
        'front-office-dashboard' => 'UI-07 / UI07-ROUTE-001 — owner UI-13; docs/frontend/audits/ui-07/defect-closure.json',
        'personnel-dashboard' => 'UI-07 / UI07-ROUTE-001 — owner UI-14; docs/frontend/audits/ui-07/defect-closure.json',
        'audit-dashboard' => 'UI-07 / UI07-ROUTE-001 — owner UI-15; docs/frontend/audits/ui-07/defect-closure.json',

        // Phase UI-08, Increment 7B. Each of these two screens was a CONSOLIDATED surface that
        // delivered several contract pages behind tabs — `platform-registration-monitoring`
        // delivered §5.4.10, §5.4.11 and §5.4.12, and `platform-promotions` delivered §5.4.6 and
        // §5.4.7 — which is the defect UI-08 exists to correct. Their route identities were
        // retired and each contract page now has its own canonical route, component and inventory
        // row, so nothing was lost: the pages were SPLIT OUT, not deleted. The legacy components
        // and their specs went with the routes because nothing referenced them any more.
        'platform-promotions' => 'UI-08 / Increment 7B — split into platform-billing-promotions and platform-billing-free-periods; docs/proof/ui-08.md',
        'platform-registration-monitoring' => 'UI-08 / Increment 7B — split into platform-merchant-registrations, platform-merchants and platform-merchant-detail; docs/proof/ui-08.md',
    ];

    $inventoryKeys = array_column($inventory['screens'], 'key');
    $claimKeys = array_column($claims, 'claim_key');

    expect(array_values(array_diff($claimKeys, $inventoryKeys, array_keys($registeredRemovals))))->toBe(
        [],
        'The audit classifies a screen that is no longer in the inventory — the register may not be rewritten, so this means a screen was REMOVED and its removal needs its own evidence.',
    );

    // A registered removal must still BE a removal. If the screen returns, this fails and the
    // entry must go.
    $resurrected = array_values(array_intersect(array_keys($registeredRemovals), $inventoryKeys));
    expect($resurrected)->toBe(
        [],
        'A screen registered as removed is back in the inventory — remove it from the registered-removal list.',
    );

    // Claims may exceed the live inventory only by the screens that were registered as removed
    // above; anything beyond that means the frozen audit was edited.
    expect(count($claims))->toBeLessThanOrEqual(
        count($inventory['screens']) + count($registeredRemovals),
        'There are more classified claims than screens plus registered removals, which is impossible unless the audit was edited.',
    );

    $keys = [];
    foreach ($claims as $claim) {
        expect(in_array($claim['classification'], UI01_CLASSIFICATIONS, true))->toBeTrue(
            "Claim {$claim['claim_key']} has classification {$claim['classification']}, which is not in the permitted vocabulary.",
        );
        expect((string) $claim['rationale'])->not->toBe('');
        expect(in_array($claim['claim_key'], $keys, true))->toBeFalse("Claim {$claim['claim_key']} is classified twice.");
        $keys[] = $claim['claim_key'];
    }

    // A row the inventory does not claim is `not_claimed` — never `false`. Reporting absence as a
    // failed claim would manufacture defects the repository never asserted.
    foreach ($claims as $claim) {
        if ($claim['claimed_status'] !== 'implemented') {
            expect($claim['classification'])->toBe(
                'not_claimed',
                "Claim {$claim['claim_key']} has inventory status {$claim['claimed_status']} and must be not_claimed.",
            );
        }
    }
});

it('reconciles all 160 required pages without conflating them with implementation claims', function (): void {
    $audit = ui01Artifact('route-component-page-audit.json');

    /** @var list<array<string, mixed>> $required */
    $required = $audit['required_pages'];

    expect($required)->toHaveCount(160, 'The binding contract is 160 required pages.');

    foreach (UI01_ACCOUNTS as $account => $count) {
        $rows = array_filter($required, static fn (array $row): bool => $row['account_key'] === $account);

        expect($rows)->toHaveCount($count, "{$account} must contribute exactly {$count} required pages.");
    }

    foreach ($required as $row) {
        expect(['claimed_by_route', 'not_claimed'])->toContain($row['required_status']);
    }

    // The two registers describe different things and are never summed.
    expect($audit['semantics'])->toHaveKey('counts_are_not_interchangeable');
    expect($audit['totals']['implementation_claims_inspected'])->not->toBe($audit['totals']['required_pages']);
});

